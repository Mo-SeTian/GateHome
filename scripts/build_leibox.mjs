import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const source=new URL('../internal/gateway/ui/leibox/',import.meta.url);
const output=new URL('../internal/gateway/web/',import.meta.url);
const read=name=>readFileSync(new URL(name,source),'utf8');
const engine=read('ai-generating/AiImageGenerationEngine.js');
const start=engine.indexOf('createSurface(target, ')+'createSurface(target, '.length;
const surface=JSON.parse(engine.slice(start,engine.indexOf(', options);',start)));
const files=['ai-generating/motion-runtime.ts','ai-generating/AiImageGenerationEngine.js','ai-generating/AiImageGeneration.ts','loader.js'];
const script=files.map(name=>{
  let text=read(name).replace(/^import .*;\r?\n/gm,'').replace(/^export type .*;\r?\n/gm,'');
  if(name.endsWith('.ts')) text=stripTypeScriptTypes(text,{mode:'strip'});
  return text.replace(/^export (?=function|class|const|let)/gm,'');
}).join('\n');
writeFileSync(new URL('leibox-ui.js',output),'/* LeiBox Dot Grid Loader. Source and attribution: internal/gateway/ui/leibox/.\n * Generated with node scripts/build_leibox.mjs; edit the source files. */\n(()=>{\n'+script+'\n})();\n');
const base=':host{display:block}[hidden]{display:none!important}*{box-sizing:border-box}.motion-frame{position:relative;transform-origin:top left;overflow:hidden}.motion-body{position:relative;width:100%;min-height:var(--motion-height)}';
const css=surface.css.replace(/(^|[,\s}>+~])(?:html|body)(?=[\s,{.#:[>])/g,'$1.motion-body').replace(/:root\b/g,'.motion-body').replace(/100(?:s|d|l)?vh/g,'var(--motion-height)').replace(/position\s*:\s*fixed/g,'position:absolute');
writeFileSync(new URL('leibox-loader.css',output),'/* LeiBox Dot Grid Loader; generated by scripts/build_leibox.mjs. */\n'+base+css+'\n.motion-body{background:transparent}.title{display:none}.container{gap:0}.card{background:transparent;box-shadow:none;border-radius:0}\n');
console.log('LeiBox loader built with external CSP-compatible styles.');
